fn bench_list_vs_uniform(c: &mut Criterion) {
    let mut group = c.benchmark_group("hsbm_game/list_vs_uniform/n2000_k20");
    let n: u32 = 2_000;
    let m: u32 = 100;
    let rho = vec![0.5, 0.5];
    let c_mat = vec![vec![0.1, 0.02], vec![0.02, 0.1]];
    let p_inter = 0.01;

    group.throughput(Throughput::Elements(u64::from(n)));
    group.bench_function("uniform", |b| {
        b.iter(|| hsbm_game(n, m, &rho, &c_mat, p_inter, 0xA5B0_1104).unwrap());
    });

    let no_macros = (n / m) as usize;
    let m_list = vec![m; no_macros];
    let rho_list = vec![rho.clone(); no_macros];
    let c_list = vec![c_mat.clone(); no_macros];
    group.throughput(Throughput::Elements(u64::from(n)));
    group.bench_function("list_equivalent", |b| {
        b.iter(|| hsbm_list_game(n, &m_list, &rho_list, &c_list, p_inter, 0xA5B0_1105).unwrap());
    });
    group.finish();
}

fn bench_list_irregular(c: &mut Criterion) {
    let mut group = c.benchmark_group("hsbm_list_game/list_irregular/n2200_jagged");
    let m_list: Vec<u32> = vec![40, 80, 120, 160, 200, 240, 280, 320, 360, 400];
    let n: u32 = m_list.iter().sum();
    // Per-macro: alternate single-cluster, two-cluster, three-cluster.
    let mut rho_list: Vec<Vec<f64>> = Vec::with_capacity(m_list.len());
    let mut c_list: Vec<Vec<Vec<f64>>> = Vec::with_capacity(m_list.len());
    for (idx, _) in m_list.iter().enumerate() {
        match idx % 3 {
            0 => {
                rho_list.push(vec![1.0]);
                c_list.push(vec![vec![0.05]]);
            }
            1 => {
                rho_list.push(vec![0.5, 0.5]);
                c_list.push(vec![vec![0.1, 0.01], vec![0.01, 0.1]]);
            }
            _ => {
                let one_third = 1.0 / 3.0;
                rho_list.push(vec![one_third, one_third, 1.0 - 2.0 * one_third]);
                c_list.push(vec![
                    vec![0.2, 0.02, 0.005],
                    vec![0.02, 0.2, 0.02],
                    vec![0.005, 0.02, 0.2],
                ]);
            }
        }
    }
    let p_inter = 0.005;
    group.throughput(Throughput::Elements(u64::from(n)));
    group.bench_function("jagged", |b| {
        b.iter(|| hsbm_list_game(n, &m_list, &rho_list, &c_list, p_inter, 0xA5B0_1106).unwrap());
    });
    group.finish();
}

criterion_group!(
    benches,
    bench_size_scaling_uniform,
    bench_density_sweep,
    bench_p_sweep,
    bench_list_vs_uniform,
    bench_list_irregular,
);
criterion_main!(benches);
