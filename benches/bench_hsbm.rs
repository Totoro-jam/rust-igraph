//! Hierarchical Stochastic Block Model benchmarks (ALGO-GN-011).
//!
//! Run: `cargo bench --bench bench_hsbm`. Results land under
//! `target/criterion/`. A snapshot of the baseline lives at
//! `.codefuse/tracking/perf/ALGO-GN-011.json`.
//!
//! Coverage:
//!   * `size_scaling/uniform_k2` — uniform variant, `m=50`, two
//!     equally-sized micro-clusters per macro, in-cluster `p=0.1`,
//!     between-cluster `p=0.02`, inter-macro `p=0.01`; sweep total
//!     `n ∈ {200, 1_000, 4_000}` (4, 20, 80 macros). Shows the
//!     `O(K · m² · c_max + macros² · p)` cost split.
//!   * `density_sweep/uniform_n2000_m50` — fixed `n=2_000, m=50`, sweep
//!     in-cluster `p ∈ {0.01, 0.05, 0.1, 0.3}`, between-cluster `0.005`,
//!     inter-macro `0.001`. Isolates the intra-macro sampler cost.
//!   * `p_sweep/uniform_n2000_m100` — fixed `n=2_000, m=100` (20
//!     macros), in/between-cluster fixed at `0.1`/`0.005`, sweep
//!     inter-macro `p ∈ {0.0, 0.01, 0.1, 0.5, 1.0}`. Shows how the
//!     macros² rectangular sampler scales.
//!   * `list_vs_uniform/n2000_k20` — same observable shape generated by
//!     `hsbm_game` and `hsbm_list_game` to verify the per-macro
//!     dispatcher overhead is small.
//!   * `list_irregular/n2000_jagged` — list variant with non-uniform
//!     macro sizes `m_list=[40, 80, 120, 160, 200, 240, 280, 320, 360,
//!     400]` (sums to `2_200`; we use `n=2_200`) and per-macro `rho`/`c`
//!     that vary in width. Stresses the heterogeneous code path.
//!
//! Throughput is reported in total vertices so wall-clock per element
//! is directly comparable to the other generator benches.

#![allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]

use criterion::{BenchmarkId, Criterion, Throughput, criterion_group, criterion_main};
use rust_igraph::{hsbm_game, hsbm_list_game};

fn bench_size_scaling_uniform(c: &mut Criterion) {
    let mut group = c.benchmark_group("hsbm_game/size_scaling/uniform_k2");
    let m: u32 = 50;
    let rho = vec![0.5, 0.5];
    let c_mat = vec![vec![0.1, 0.02], vec![0.02, 0.1]];
    let p_inter = 0.01;
    for n in [200u32, 1_000, 4_000] {
        group.throughput(Throughput::Elements(u64::from(n)));
        group.bench_with_input(BenchmarkId::from_parameter(n), &n, |b, _| {
            b.iter(|| hsbm_game(n, m, &rho, &c_mat, p_inter, 0xA5B0_1101).unwrap());
        });
    }
    group.finish();
}

fn bench_density_sweep(c: &mut Criterion) {
    let mut group = c.benchmark_group("hsbm_game/density_sweep/uniform_n2000_m50");
    let n: u32 = 2_000;
    let m: u32 = 50;
    let rho = vec![0.5, 0.5];
    let p_inter = 0.001;
    for p_in in [0.01_f64, 0.05, 0.1, 0.3] {
        let c_mat = vec![vec![p_in, 0.005], vec![0.005, p_in]];
        let label = format!("pin{p_in:.2}");
        group.throughput(Throughput::Elements(u64::from(n)));
        group.bench_with_input(BenchmarkId::from_parameter(label), &p_in, |b, _| {
            b.iter(|| hsbm_game(n, m, &rho, &c_mat, p_inter, 0xA5B0_1102).unwrap());
        });
    }
    group.finish();
}

